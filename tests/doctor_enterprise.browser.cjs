// Real public ZIP, geometric IFC, native purpose worker and immutable records.
const assert = require("node:assert/strict");
const fs = require("node:fs");
const path = require("node:path");
const { launchBrowser, captureFailure } = require("./browser-qa-helpers.cjs");

async function main() {
  const [base, evidence, fixtures] = process.argv.slice(2);
  assert.ok(base && evidence && fixtures);
  fs.mkdirSync(evidence, { recursive: true });
  const browser = await launchBrowser(evidence);
  const errors = [];
  const observations = [];
  const page = await browser.newPage({ viewport: { width: 1440, height: 1000 } });
  page.on("pageerror", error => errors.push(error.message));
  const get = async url => { const response = await page.request.get(base + url); assert.ok(response.ok(), `${url} ${response.status()} ${await response.text()}`); return response.json(); };
  const post = async (url, data, binary = false) => { const response = await page.request.post(base + url, binary ? { headers: { "Content-Type": "application/octet-stream" }, data } : { data }); assert.ok(response.ok(), `${url} ${response.status()} ${await response.text()}`); return response.json(); };
  const capture = name => page.screenshot({ path: path.join(evidence, `${name}.png`) });
  const rulesURL = project => `${base}/projects.html?lang=en&project=${project}&tab=rules`;
  const purposeURL = project => `${base}/projects.html?lang=en&project=${project}&tab=purpose`;
  try {
    const project = await post("/api/projects", { name: "PUBLIC SYNTHETIC · enterprise purpose browser" });
    const before = await post("/api/review/models?filename=PUBLIC-SYNTHETIC-before.ifc", fs.readFileSync(path.join(fixtures, "PUBLIC-SYNTHETIC-before.ifc")), true);
    const first = await post("/api/projects/revisions", { project_id: project.project_id, model_name: "PUBLIC SYNTHETIC · source model", label: "R1 · source baseline", review_id: before.review_id });
    const after = await post("/api/review/models?filename=PUBLIC-SYNTHETIC-after.ifc", fs.readFileSync(path.join(fixtures, "PUBLIC-SYNTHETIC-after.ifc")), true);
    const second = await post("/api/projects/revisions", { project_id: project.project_id, model_id: first.revision.model_id, label: "R2 · source parameter change", review_id: after.review_id });
    const bulkBody = fs.readFileSync(path.join(fixtures, "PUBLIC-BULK.ifc"));
    const bulkReport = await post("/api/review/models?filename=PUBLIC-BULK.ifc", bulkBody, true);
    const bulkRevision = await post("/api/projects/revisions", { project_id: project.project_id, model_name: "PUBLIC SYNTHETIC · finite blocker register", label: "R1 · 150 actual meshes", review_id: bulkReport.review_id });
    await page.goto(rulesURL(project.project_id));
    await page.locator("#project-rules-file").setInputFiles({ name: "invalid.zip", mimeType: "application/zip", buffer: Buffer.from("public invalid zip") });
    await page.locator(".enterprise-panel .project-form-message.is-error").waitFor();
    await page.locator("#project-rules-file").setInputFiles(path.join(fixtures, "public-rules.zip"));
    await page.locator("#rules-confirmed-by").waitFor();
    assert.ok((await page.locator(".enterprise-rule-content").innerText()).includes("BIM Doctor public example"));
    await page.getByRole("button", { name: "Adopt this rule revision", exact: true }).click();
    assert.equal(await page.locator("#rules-confirmed-by").getAttribute("aria-invalid"), "true");
    await page.locator("#rules-confirmed-by").fill("Public fixture reviewer");
    await page.locator("#rules-responsible-team").fill("Public fixture coordination team");
    await page.route("**/api/projects/rules/confirm", route => route.fulfill({ status: 503, json: { error: "Controlled adoption outage" } }));
    await page.getByRole("button", { name: "Adopt this rule revision", exact: true }).click();
    await page.locator("#rules-confirm-message.is-error").waitFor();
    assert.equal(await page.locator("#rules-confirmed-by").inputValue(), "Public fixture reviewer");
    await page.unroute("**/api/projects/rules/confirm");
    await page.getByRole("button", { name: "Adopt this rule revision", exact: true }).click();
    await page.waitForURL(url => !!url.searchParams.get("rule_revision"));
    const adopted = new URL(page.url()).searchParams.get("rule_revision");
    await page.locator(".enterprise-rule-content").filter({ hasText: "Public fixture coordination team" }).waitFor();
    await page.locator(".enterprise-rule-content > section").first().scrollIntoViewIfNeeded();
    await capture("enterprise-en-rules-adopted");
    await page.goto(purposeURL(project.project_id));
    await page.locator("#purpose-rule-revision option").first().waitFor({ state: "attached" });
    await page.locator("#purpose-revision").selectOption(first.revision.revision_id);
    await page.locator("#purpose-id").selectOption("terminal-schedule");
    assert.equal(await page.getByRole("button", { name: "Run purpose review", exact: true }).isEnabled(), false, "old snapshot cannot recheck rules until exact source is retained");
    await page.locator("#purpose-source-file").setInputFiles(path.join(fixtures, "PUBLIC-SYNTHETIC-after.ifc"));
    await page.locator(".enterprise-source").getByRole("link", { name: "Import as a new model revision", exact: true }).waitFor();
    assert.equal((await get(`/api/projects/purpose?project=${project.project_id}`)).sources.find(item => item.revision_id === first.revision.revision_id).source_available, false);
    await page.locator("#purpose-source-file").setInputFiles(path.join(fixtures, "PUBLIC-SYNTHETIC-before.ifc"));
    await page.locator(".enterprise-source").filter({ hasText: "Source IFC retained locally" }).waitFor();
    async function selectA() {
      await page.locator("#purpose-scope-kind").selectOption("elements");
      await page.locator("#purpose-object-search").fill("terminal A");
      await page.getByRole("checkbox", { name: /terminal A/ }).check();
    }
    async function runReview() {
      const previous = await page.locator("[data-run]").count() ? await page.locator("[data-run]").getAttribute("data-run") : null;
      await page.locator(".enterprise-form > .enterprise-actions").getByRole("button", { name: /Run purpose review|Reassess this purpose/ }).click();
      await page.waitForFunction(previous => { const node = document.querySelector("[data-run]"); return node && node.dataset.run !== previous; }, previous);
      return get(`/api/projects/purpose/run?run=${await page.locator("[data-run]").getAttribute("data-run")}`);
    }
    await selectA();
    const blocked = await runReview();
    assert.equal(blocked.conclusion.status, "BLOCKED", "one passed condition cannot satisfy the other failed condition");
    assert.equal(blocked.conclusion.scope_count, 1);
    assert.ok(Object.values(blocked.conclusion.counts).reduce((sum, count) => sum + count, 0) > blocked.conclusion.scope_count, "evidence observations and object counts remain distinct");
    const firstProblem = page.locator(".enterprise-blocker").first();
    assert.equal(await firstProblem.locator("h3").innerText(), blocked.blockers[0].element_name, "the problem list leads with the affected object, not an opaque rule ID");
    assert.equal(await firstProblem.locator(".enterprise-facts").isVisible(), true, "required, actual and next action are visible without opening technical data");
    assert.equal(await firstProblem.locator(".enterprise-facts dd").count(), 3);
    assert.equal(await firstProblem.locator(".enterprise-technical").evaluate(node => node.open), false, "raw diagnostic data starts folded");
    assert.match(await page.locator(".enterprise-problem-summary").innerText(), /Objects needing attention[\s\S]*Unmet machine checks/);
    await page.locator("[data-run]").scrollIntoViewIfNeeded();
    await capture("enterprise-en-blocked");
    await firstProblem.scrollIntoViewIfNeeded();
    await capture("enterprise-en-actionable-blocker");
    await page.locator(".enterprise-blocker").first().getByRole("link", { name: "Locate in 3D", exact: true }).click();
    await page.locator(".review-status").filter({ hasText: "Model loaded" }).waitFor();
    assert.equal(new URL(page.url()).searchParams.has("finding"), false);
    assert.equal(await page.locator(".review-finding.is-selected[data-purpose-finding]").count(), 1);
    assert.equal(await page.getByRole("button", { name: "Focus element", exact: true }).isEnabled(), true);
    await page.getByRole("button", { name: "Focus element", exact: true }).click();
    await page.getByRole("button", { name: "Isolate element", exact: true }).click();
    assert.match(await page.locator(".review-view-footer").innerText(), /Visible elements: 1/);
    await capture("enterprise-en-purpose-3d");
    await page.getByRole("link", { name: "Back to purpose review", exact: true }).click();
    await page.locator("[data-run]").waitFor();
    await page.locator("#purpose-revision").selectOption(second.revision.revision_id);
    await page.locator("#purpose-source-file").setInputFiles(path.join(fixtures, "PUBLIC-SYNTHETIC-after.ifc"));
    await page.locator(".enterprise-source").filter({ hasText: "Source IFC retained locally" }).waitFor();
    await page.locator("#purpose-id").selectOption("terminal-schedule");
    await selectA();
    await page.locator("#purpose-prior").selectOption(blocked.run_id);
    const ready = await runReview();
    assert.equal(ready.conclusion.status, "READY");
    assert.ok(ready.change_summary.outcomes.some(item => item.change === "rule_recheck_passed"));
    assert.ok(await page.locator('.enterprise-change-row[data-change="rule_recheck_passed"]').count());
    assert.equal(await page.locator(".enterprise-change-details").evaluate(node => node.open), false, "per-observation changes start folded under the summary");
    await page.locator(".enterprise-change-details > summary").click();
    assert.match(await page.locator(".enterprise-changes").innerText(), /Same machine rule passed on recheck/);
    await page.locator("#purpose-id").selectOption("tender-submission");
    await selectA();
    const unknown = await runReview();
    assert.equal(unknown.conclusion.status, "UNKNOWN");
    const manual = page.locator(".enterprise-manual-form").first();
    await manual.getByLabel("Determination", { exact: true }).selectOption("confirmed");
    await manual.getByLabel("Recorded by", { exact: true }).fill("Public fixture reviewer");
    await manual.getByLabel("Basis", { exact: true }).fill("Public synthetic source parameters and exact exported object reviewed.");
    await manual.getByLabel("Evidence reference", { exact: true }).fill("PUBLIC-SYNTHETIC source / terminal A");
    await page.getByRole("link", { name: "Project rules", exact: true }).click();
    await page.locator(".project-draft-dialog[open]").waitFor();
    await page.getByRole("button", { name: "Keep editing", exact: true }).click();
    await page.route("**/api/projects/purpose/determinations", route => route.fulfill({ status: 503, json: { error: "Controlled evidence save outage" } }));
    await manual.getByRole("button", { name: "Save human evidence", exact: true }).click();
    await manual.locator(".project-form-message.is-error").waitFor();
    assert.match(await manual.getByLabel("Basis", { exact: true }).inputValue(), /exact exported object/);
    await page.unroute("**/api/projects/purpose/determinations");
    await manual.getByRole("button", { name: "Save human evidence", exact: true }).click();
    await manual.getByText(/Human evidence saved/).waitFor();
    assert.equal((await get(`/api/projects/purpose/run?run=${unknown.run_id}`)).conclusion.status, "UNKNOWN", "saving a human record never edits the sealed old verdict");
    await page.locator("[data-run]").getByRole("button", { name: "Reassess this purpose", exact: true }).click();
    await page.locator(".enterprise-form").getByRole("button", { name: "Reassess this purpose", exact: true }).waitFor();
    assert.equal(await page.getByRole("checkbox", { name: /terminal A/ }).isChecked(), true, "stable purpose scope restores the exact base-review checkbox through the supplied mapping");
    assert.equal(await page.locator(".enterprise-object-list input:checked").count(), 1);
    const humanReady = await runReview();
    assert.equal(humanReady.conclusion.status, "READY");
    assert.ok(humanReady.change_summary.outcomes.some(item => item.change === "evidence_updated"));
    assert.ok(await page.locator('.enterprise-change-row[data-change="evidence_updated"]').count());
    await page.locator(".enterprise-change-details > summary").click();
    assert.match(await page.locator(".enterprise-changes").innerText(), /Human evidence changed/);
    assert.ok(humanReady.determinations.some(item => item.determiner === "Public fixture reviewer"));
    await page.locator("[data-run]").scrollIntoViewIfNeeded();
    await capture("enterprise-en-human-evidence");
    const downloadPromise = page.waitForEvent("download");
    await page.getByRole("link", { name: "Download this purpose brief", exact: true }).click();
    await (await downloadPromise).saveAs(path.join(evidence, "purpose-brief.md"));
    // Controlled job transport uses a real immutable run; no fabricated verdict.
    let jobState = "running";
    let purposePosts = 0;
    let purposeCancels = 0;
    let jobId = null;
    let failStatus = false;
    let rejectJob = false;
    let completeOnCancel = false;
    let resultRun = humanReady.run_id;
    const runsPath = url => url.pathname === "/api/projects/purpose/runs";
    const jobsPath = url => url.pathname === "/api/projects/purpose/jobs";
    const descriptor = () => ({ job_id: jobId, state: jobState, stage: "checking", completed: 0, total: 0, result: { run_id: resultRun } });
    await page.route(runsPath, route => {
      purposePosts++; jobId = route.request().postDataJSON().job_id; assert.match(jobId, /^[0-9a-f-]{36}$/);
      if (rejectJob) return route.fulfill({ status: 409, json: { error: "Other page has an active job", active_job_id: "foreign-public-job" } });
      return route.fulfill({ status: 202, json: { ...descriptor(), state: "queued" } });
    });
    await page.route(jobsPath, route => failStatus ? (failStatus = false, route.fulfill({ status: 503, json: { error: "Controlled purpose status outage" } })) : route.fulfill({ json: descriptor() }));
    await page.route("**/api/projects/purpose/jobs/cancel", route => { purposeCancels++; assert.equal(route.request().postDataJSON().job_id, jobId); jobState = completeOnCancel ? "succeeded" : "cancelling"; return route.fulfill({ json: descriptor() }); });
    const controls = page.locator(".enterprise-form > .enterprise-actions");
    await controls.getByRole("button", { name: /Run purpose review|Reassess this purpose/ }).click();
    await page.locator(".enterprise-job-status").filter({ hasText: "Running purpose review" }).waitFor();
    await controls.getByRole("button", { name: "Cancel review", exact: true }).click();
    await page.locator(".enterprise-job-status").filter({ hasText: "waiting for service confirmation" }).waitFor();
    assert.equal(await page.locator("[data-run]").getAttribute("data-run"), humanReady.run_id);
    jobState = "cancelled";
    await page.locator(".enterprise-job-status").filter({ hasText: "Purpose review stopped" }).waitFor();
    assert.equal(purposeCancels, 1);
    jobState = "running"; failStatus = true;
    await controls.getByRole("button", { name: /Run purpose review|Reassess this purpose/ }).click();
    await page.locator(".enterprise-job-status.is-error").waitFor();
    const postsBeforeResume = purposePosts;
    jobState = "succeeded";
    await controls.getByRole("button", { name: "Retry", exact: true }).click();
    await page.locator(".enterprise-job-status").filter({ hasText: "Saved" }).waitFor();
    assert.equal(purposePosts, postsBeforeResume, "purpose status retry resumes the client UUID without resubmission");
    jobState = "running"; completeOnCancel = true; resultRun = unknown.run_id;
    await controls.getByRole("button", { name: /Run purpose review|Reassess this purpose/ }).click();
    await page.locator(".enterprise-job-status").filter({ hasText: "Running purpose review" }).waitFor();
    await controls.getByRole("button", { name: "Cancel review", exact: true }).click();
    await page.locator(".enterprise-job-status").filter({ hasText: "Review completed before cancellation" }).waitFor();
    assert.equal(await page.locator("[data-run]").getAttribute("data-run"), humanReady.run_id, "late successful purpose run remains in history without replacing the displayed record");
    assert.equal(new URL(page.url()).searchParams.get("assessment"), humanReady.run_id);
    assert.doesNotMatch(await page.locator(".enterprise-job-status").innerText(), /review stopped/);
    completeOnCancel = false;
    rejectJob = true;
    await controls.getByRole("button", { name: /Run purpose review|Reassess this purpose/ }).click();
    await page.locator(".enterprise-job-status.is-error").waitFor();
    assert.equal(await controls.getByRole("button", { name: "Cancel review", exact: true }).isVisible(), false);
    assert.equal(purposeCancels, 2, "another page's active task is never cancelled");
    await page.unroute(runsPath); await page.unroute(jobsPath); await page.unroute("**/api/projects/purpose/jobs/cancel");
    await page.goto(rulesURL(project.project_id));
    await page.locator("#project-rules-file").setInputFiles(path.join(fixtures, "public-unsupported-rules.zip"));
    await page.locator("#rules-confirmed-by").waitFor();
    assert.ok(await page.locator(".enterprise-status.state-unsupported").count());
    await page.locator("#rules-confirmed-by").fill("Public fixture reviewer");
    await page.locator("#rules-responsible-team").fill("Public fixture coordination team");
    await page.getByRole("button", { name: "Adopt this rule revision", exact: true }).click();
    await page.waitForURL(url => !!url.searchParams.get("rule_revision") && url.searchParams.get("rule_revision") !== adopted);
    const unsupported = new URL(page.url()).searchParams.get("rule_revision");
    await page.goto(purposeURL(project.project_id));
    await page.locator("#purpose-rule-revision").selectOption(unsupported);
    await page.locator("#purpose-id").selectOption("terminal-schedule");
    await page.locator("#purpose-revision").selectOption(second.revision.revision_id);
    await selectA();
    await page.locator("#purpose-prior").selectOption(ready.run_id);
    const unsupportedRun = await runReview();
    assert.equal(unsupportedRun.conclusion.status, "UNKNOWN");
    assert.ok(unsupportedRun.change_summary.basis_changes.length > 0);
    assert.equal(unsupportedRun.change_summary.outcomes.some(item => item.change === "rule_recheck_passed"), false, "changed rule basis is not a model repair");
    await page.locator("#purpose-id").selectOption("mep-to-architecture");
    await selectA();
    const missingCounterpart = await runReview();
    assert.equal(missingCounterpart.conclusion.status, "UNKNOWN");
    assert.match(JSON.stringify(missingCounterpart.refusal || missingCounterpart.conclusion.caveats), /counterpart|consumer|recipient/i);
    assert.match(await page.locator(".enterprise-blockers").innerText(), /not been fully assessed/, "refused assessment must not look like an empty successful problem list");
    assert.equal(await page.locator(".enterprise-blockers .enterprise-problem-summary dd").count(), 0, "missing context must not be presented as four zero counts");
    await page.goto(`${base}/review.html?lang=en&revision=${missingCounterpart.revision_id}&assessment=${missingCounterpart.run_id}`);
    await page.locator(".review-status").filter({ hasText: "Model loaded" }).waitFor();
    assert.match(await page.locator(".enterprise-purpose-context").innerText(), /counterpart|consumer|recipient/i, "3D context preserves the concrete refusal reason");
    await page.getByRole("link", { name: "Back to purpose review", exact: true }).click();
    await page.locator("[data-run]").waitFor();
    await page.setViewportSize({ width: 390, height: 844 });
    await page.getByRole("button", { name: "中文", exact: true }).click();
    await page.locator("[data-run]").waitFor();
    assert.equal(new URL(page.url()).searchParams.get("assessment"), missingCounterpart.run_id);
    assert.ok(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth));
    await page.locator("[data-run]").scrollIntoViewIfNeeded();
    await capture("enterprise-zh-390-purpose");
    await page.goto(purposeURL(project.project_id));
    await page.locator("#purpose-rule-revision").selectOption(adopted);
    await page.locator("#purpose-id").selectOption("terminal-schedule");
    await page.locator("#purpose-revision").selectOption(bulkRevision.revision.revision_id);
    await page.locator("#purpose-source-file").setInputFiles(path.join(fixtures, "PUBLIC-BULK.ifc"));
    await page.locator(".enterprise-source").filter({ hasText: "Source IFC retained locally" }).waitFor();
    await page.locator("#purpose-scope-kind").selectOption("all");
    const bulk = await runReview();
    assert.equal(bulk.conclusion.scope_count, 150);
    assert.ok(bulk.blockers.length > 100);
    assert.equal(await page.locator(".enterprise-blockers .enterprise-blocker").count(), 100);
    await page.locator(".enterprise-more-blockers").click();
    assert.equal(await page.locator(".enterprise-blockers .enterprise-blocker").count(), bulk.blockers.length);
    await page.locator("[data-run]").getByRole("button", { name: "Reassess this purpose", exact: true }).click();
    await page.locator(".enterprise-form").getByRole("button", { name: "Reassess this purpose", exact: true }).waitFor();
    const bulkAgain = await runReview();
    assert.equal(await page.locator(".enterprise-change-row").count(), 100);
    await page.locator(".enterprise-change-details > summary").click();
    await page.locator(".enterprise-more-changes").click();
    assert.equal(await page.locator(".enterprise-change-row").count(), Math.min(200, bulkAgain.change_summary.outcomes.length));
    while (await page.locator(".enterprise-more-changes").count()) await page.locator(".enterprise-more-changes").click();
    assert.equal(await page.locator(".enterprise-change-row").count(), bulkAgain.change_summary.outcomes.length);
    const target = bulkAgain.blockers.at(-1);
    await page.goto(`${base}/review.html?lang=en&revision=${bulkRevision.revision.revision_id}&assessment=${bulkAgain.run_id}&purpose_finding=${target.blocker_id}`);
    await page.locator(".review-status").filter({ hasText: "Model loaded" }).waitFor();
    assert.equal(await page.locator(".review-finding").count(), 100);
    assert.equal(await page.locator(".review-finding").first().getAttribute("data-purpose-finding"), target.blocker_id);
    assert.equal(await page.locator(".review-finding.is-selected").count(), 1);
    await page.locator("#review-search").fill("no-purpose-match-public-test");
    assert.match(await page.locator("#review-findings").innerText(), /No purpose evidence matches/);
    assert.equal(await page.locator(".review-finding.is-selected").count(), 0);
    assert.equal(await page.locator(".review-outside").isVisible(), true);
    await page.getByRole("button", { name: "Clear search", exact: true }).click();
    assert.equal(await page.locator(".review-finding").first().getAttribute("data-purpose-finding"), target.blocker_id);
    assert.equal(await page.getByRole("button", { name: "Focus element", exact: true }).isEnabled(), true);
    await page.getByRole("button", { name: "Focus element", exact: true }).click();
    await capture("enterprise-bulk-exact-purpose-selection");
    const otherProject = await post("/api/projects", { name: "PUBLIC SYNTHETIC · independent project context" });
    await page.goto(`${purposeURL(project.project_id)}&assessment=${bulkAgain.run_id}`);
    await page.locator("[data-run]").waitFor();
    await page.getByRole("button", { name: /PUBLIC SYNTHETIC · independent project context/ }).click();
    await page.locator(".project-detail-heading h2").filter({ hasText: otherProject.name }).waitFor();
    assert.equal(new URL(page.url()).searchParams.has("assessment"), false, "changing project clears the prior project's assessment before mounting its purpose panel");
    assert.equal(await page.locator("[data-run]").count(), 0);
    assert.deepEqual(errors, []);
    observations.push("Real public geometric IFCs: exact source SHA attachment, two simultaneous requirements, blocked 3D deep link, same-slot source revision recheck, explicit manual save versus reassessment, immutable verdict, unsupported adoption UNKNOWN, missing counterpart, localized 390px and brief.");
    fs.writeFileSync(path.join(evidence, "enterprise-browser.json"), JSON.stringify({ passed: true, project_id: project.project_id, rule_revision_id: adopted, runs: [blocked.run_id, ready.run_id, unknown.run_id, humanReady.run_id, unsupportedRun.run_id], observations, errors }, null, 2));
    console.log(JSON.stringify({ passed: true, observations, errors }));
  } catch (error) { await captureFailure(browser, evidence, error); throw error; }
  finally { await browser.close(); }
}
main().catch(error => { console.error(error); process.exitCode = 1; });
