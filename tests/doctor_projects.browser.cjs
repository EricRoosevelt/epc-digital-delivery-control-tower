// Persistent project workflow against a real Doctor server. No fake IFC results.
// node tests/doctor_projects.browser.cjs URL evidence-dir synthetic-fixture.json
// Prepare the last argument with doctor_projects_fixture.py before running.
const assert = require("node:assert/strict");
const fs = require("node:fs");
const path = require("node:path");
const { chromium } = require("playwright");
const { captureFailure, browserOptions } = require("./browser-qa-helpers.cjs");

async function main() {
  const [base, evidence, fixturePath] = process.argv.slice(2);
  assert.ok(base && evidence && fixturePath, "Supply URL, evidence directory and synthetic fixture JSON");
  fs.mkdirSync(evidence, { recursive: true });
  const fixture = JSON.parse(fs.readFileSync(fixturePath, "utf8"));
  assert.equal(fixture.synthetic, true);
  const browser = await chromium.launch(browserOptions());
  const errors = [];
  const observations = [];
  const capture = (page, name) => page.screenshot({ path: path.join(evidence, `${name}.png`) });
  const loaded = page => page.locator(".review-status").filter({ hasText: /Model loaded|模型已载入/ }).waitFor();
  try {
    const page = await browser.newPage({ viewport: { width: 1440, height: 1000 } });
    page.on("pageerror", error => errors.push(error.message));
    await page.goto(`${base}/projects.html?lang=en`);
    await page.locator("#project-name").waitFor();
    await page.getByRole("button", { name: "Create project", exact: true }).click();
    assert.equal(await page.locator("#project-name").getAttribute("aria-invalid"), "true");
    const projectName = `Browser IFC coordination ${Date.now()}`;
    await page.locator("#project-name").fill(projectName);
    await page.getByRole("button", { name: "Create project", exact: true }).click();
    await page.locator(".project-detail-heading h2").filter({ hasText: projectName }).waitFor();
    const projectId = new URL(page.url()).searchParams.get("project");
    assert.ok(projectId);
    await capture(page, "projects-en-empty-project");
    await page.getByRole("link", { name: "Add IFC model", exact: true }).click();
    await page.getByRole("button", { name: "Load public example", exact: true }).click();
    await loaded(page);
    await page.locator(".project-review-context").getByRole("button", { name: "Save to project", exact: true }).click();
    await page.locator("#save-project").waitFor();
    assert.equal(await page.locator("#save-project").inputValue(), projectId);
    await page.locator("#save-model-name").fill("Public example · three disciplines");
    await page.locator("#save-revision-label").fill("R1 · public baseline");
    await capture(page, "review-en-save-revision");
    await page.getByRole("button", { name: "Save model revision", exact: true }).click();
    await page.locator(".project-context-status").filter({ hasText: "Saved model revision" }).waitFor();
    const savedRevisionId = new URL(page.url()).searchParams.get("revision");
    const findingId = new URL(page.url()).searchParams.get("finding");
    assert.ok(savedRevisionId && findingId);
    let detailResponse = await (await page.request.get(`${base}/api/projects/detail?project=${projectId}`)).json();
    assert.equal(detailResponse.models.length, 1);
    assert.equal(detailResponse.models[0].revisions.length, 1);
    const modelId = detailResponse.models[0].model_id;
    await page.locator(".project-followup > summary").click();
    await page.locator("#followup-status").selectOption("ready_for_recheck");
    await page.locator("#followup-owner").fill("王工 / HVAC coordination");
    const savedNote = "Check the cap classification in the source model.\nRe-export after coordination; this note is not a passed recheck.";
    await page.locator("#followup-note").fill(savedNote);
    await page.getByRole("button", { name: "Save follow-up", exact: true }).click();
    await page.locator(".project-followup-form .project-form-message").filter({ hasText: "Follow-up saved" }).waitFor();
    assert.equal(await page.locator(".review-evidence .review-verdict").innerText(), "FAIL", "manual ready_for_recheck must not change the IFC verdict");
    const draftNote = `${savedNote}\nUnsaved coordination draft.`;
    await page.locator("#followup-note").fill(draftNote);
    await page.locator(".review-finding").nth(1).click();
    await page.locator(".review-finding").first().click();
    assert.equal(await page.locator("#followup-note").inputValue(), draftNote, "switching findings preserves the draft");
    await page.getByRole("button", { name: "中文", exact: true }).click();
    await page.locator(".project-draft-dialog[open]").waitFor();
    assert.equal(await page.getByRole("button", { name: "Keep editing", exact: true }).evaluate(el => el === document.activeElement), true);
    await capture(page, "review-en-unsaved-draft");
    await page.getByRole("button", { name: "Keep editing", exact: true }).click();
    assert.equal(await page.locator("#followup-note").inputValue(), draftNote);
    await page.route("**/api/projects/followup", route => route.fulfill({ status: 503, contentType: "application/json", body: JSON.stringify({ error: "Temporary test failure" }) }));
    await page.getByRole("button", { name: "Save follow-up", exact: true }).click();
    await page.locator(".project-followup-form .project-form-message.is-error").waitFor();
    assert.equal(await page.locator("#followup-note").inputValue(), draftNote);
    await page.unroute("**/api/projects/followup");
    await page.getByRole("button", { name: "Save follow-up", exact: true }).click();
    await page.locator(".project-followup-form .project-form-message").filter({ hasText: "Follow-up saved" }).waitFor();
    await page.getByRole("button", { name: "中文", exact: true }).click();
    await loaded(page);
    assert.equal(new URL(page.url()).searchParams.get("revision"), savedRevisionId);
    assert.equal(new URL(page.url()).searchParams.get("finding"), findingId);
    await page.locator(".project-followup > summary").click();
    assert.equal(await page.locator("#followup-status").inputValue(), "ready_for_recheck");
    assert.equal(await page.locator("#followup-note").inputValue(), draftNote);
    assert.equal(await page.locator("#followup-owner").inputValue(), "王工 / HVAC coordination");
    await capture(page, "review-zh-saved-followup");
    await page.goto(`${base}/review.html?lang=en&project=${projectId}&model=${modelId}`);
    await page.locator("#review-file").setInputFiles(path.resolve(__dirname, "../data/raw/Building-Hvac.ifc"));
    await loaded(page);
    await page.locator(".project-review-context").getByRole("button", { name: "Save to project", exact: true }).click();
    await page.waitForFunction(expected => document.querySelector("#save-model")?.value === expected, modelId);
    await page.locator("#save-revision-label").fill("R2 · HVAC export");
    await page.getByRole("button", { name: "Save model revision", exact: true }).click();
    await page.locator(".project-context-status").filter({ hasText: "Saved model revision" }).waitFor();
    const laterRevision = new URL(page.url()).searchParams.get("revision");
    assert.notEqual(laterRevision, savedRevisionId);
    detailResponse = await (await page.request.get(`${base}/api/projects/detail?project=${projectId}`)).json();
    assert.equal(detailResponse.models.length, 1, "new revision stays in the chosen logical model");
    assert.equal(detailResponse.models[0].revisions.length, 2);
    await page.getByRole("link", { name: "Back to project", exact: false }).click();
    await page.locator(".project-revision-row").first().waitFor();
    await capture(page, "projects-en-model-revisions");
    const brief = await page.request.get(`${base}/api/projects/brief?project=${projectId}&language=en`);
    assert.equal(brief.status(), 200);
    assert.match(brief.headers()["content-type"], /text\/markdown/);
    assert.match(await brief.text(), /HVAC|王工/);
    observations.push("Real public IFC: project creation and validation, save model revision, owner/status/multiline note, retained finding drafts, unsaved-change dialog, failed-save retry, language reopening, same-model new revision, Markdown brief.");

    const comparisonURL = `${base}/projects.html?lang=en&project=${fixture.project_id}&before=${fixture.before_revision}&after=${fixture.after_revision}`;
    await page.goto(comparisonURL);
    await page.locator(".project-change-count").first().waitFor();
    assert.equal(await page.locator(".project-change-count").count(), 6, "deep link starts comparison after DOM mount");
    await capture(page, "projects-en-comparison");
    const comparison = await (await page.request.get(`${base}/api/projects/compare?before=${fixture.before_revision}&after=${fixture.after_revision}`)).json();
    for (const change of ["resolved", "remaining", "new", "missing", "not_comparable"]) {
      await page.locator(`.project-change-count.change-${change}`).click();
      const expected = comparison.rows.filter(row => row.severity === "ERROR" && row.change === change).length;
      assert.ok(expected > 0, `${change} has real synthetic evidence`);
      assert.equal(await page.locator(".project-change-row").count(), expected);
      if (change === "missing") {
        assert.match(await page.locator(".project-comparison-hint").innerText(), /not a repair/);
        const link = page.locator(".project-change-row a").first();
        assert.match(await link.getAttribute("href"), new RegExp(fixture.before_revision));
        await capture(page, "projects-en-missing-not-repaired");
      }
    }
    await page.locator(".project-change-count.change-resolved").click();
    await page.locator(".project-change-row a").first().click();
    await loaded(page);
    assert.equal(new URL(page.url()).searchParams.get("revision"), fixture.after_revision);
    assert.equal(await page.locator(".review-evidence .review-verdict").innerText(), "PASS");
    assert.equal(await page.locator(".review-geometry-note").count(), 1, "synthetic object has no invented geometry");
    await page.goto(comparisonURL.replace("lang=en", "lang=zh"));
    await page.setViewportSize({ width: 390, height: 844 });
    await page.locator(".project-change-count").first().waitFor();
    assert.ok(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), "phone comparison has no horizontal overflow");
    await page.locator(".project-comparison-categories").scrollIntoViewIfNeeded();
    await capture(page, "projects-zh-390-comparison");
    await page.locator(".project-change-count.change-missing").click();
    await page.locator(".project-change-row a").first().click();
    await loaded(page);
    assert.equal(new URL(page.url()).searchParams.get("revision"), fixture.before_revision);
    await page.locator(".review-right").scrollIntoViewIfNeeded();
    await capture(page, "review-zh-390-revision-evidence");
    assert.ok(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth));
    await page.emulateMedia({ reducedMotion: "reduce" });
    await page.getByRole("link", { name: "返回项目", exact: false }).click();
    await page.locator(".project-detail-heading").waitFor();
    await capture(page, "projects-zh-390-revisions");
    observations.push("Real synthetic IFC comparisons: FAIL to PASS, remaining, new, disappearance not repair, class not comparable, six categories, automatic comparison deep link, exact finding/revision links, no fake geometry, Chinese 390px and reduced motion.");
    assert.deepEqual(errors, []);
    const output = { observations, errors, project_id: projectId, model_id: modelId, revision_id: savedRevisionId, later_revision_id: laterRevision, finding_id: findingId, saved_note: draftNote };
    fs.writeFileSync(path.join(evidence, "projects-browser.json"), JSON.stringify(output, null, 2));
    console.log(JSON.stringify({ passed: true, ...output }, null, 2));
  } catch (error) { await captureFailure(browser, evidence, error); throw error; }
  finally { await browser.close(); }
}
main().catch(error => { console.error(error); process.exitCode = 1; });
